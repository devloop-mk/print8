import type { Product } from '@/lib/data/catalog';

/** Supplier mockup image (see scripts/fetch-koni-product-images.mjs). */
export function supplierCatalogImage(sku: string): string {
  const file = `${sku.trim().toUpperCase().replace(/[^A-Z0-9]+/g, '-')}.jpg`;
  return `/supplier/koni/${file}`;
}

/** Lifestyle + plain supplier gallery for upload-only puzzles. */
export function puzzleGalleryImages(
  puzzleId: string,
  sku: string,
  color: string,
) {
  return {
    [color]: {
      primary: `/puzzles/${puzzleId}-lifestyle.jpg`,
      secondary: supplierCatalogImage(sku),
    },
  };
}

