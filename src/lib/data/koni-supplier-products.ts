/** Public mockup path for a Koni SKU (run scripts/fetch-koni-product-images.mjs). */
export function koniSupplierImage(sku: string): string {
  const file = `${sku.trim().toUpperCase().replace(/[^A-Z0-9]+/g, '-')}.jpg`;
  return `/supplier/koni/${file}`;
}

